def _render_codex_router(manifest: dict) -> str:
    lines = [
        GENERATOR_TAG.rstrip(),
        "",
        CODEX_ROUTER_HEADER.rstrip(),
        "",
        *_render_codex_router_body(manifest),
        "",
    ]
    return "\n".join(lines)


def _render_codex_router_embed(manifest: dict) -> str:
    lines = [
        GENERATOR_TAG.rstrip(),
        "",
        *_render_codex_router_body(manifest),
        "",
    ]
    return "\n".join(lines)


def _replace_marked_block(content: str, replacement: str) -> tuple[str, bool]:
    begin = content.find(CODEX_ROUTER_BEGIN)
    end = content.find(CODEX_ROUTER_END)
    if begin == -1 or end == -1 or end < begin:
        raise ValueError("missing codex router markers")
    if (
        content.find(CODEX_ROUTER_BEGIN, begin + 1) != -1
        or content.find(CODEX_ROUTER_END, end + 1) != -1
    ):
        raise ValueError("multiple codex router marker blocks")

    block_start = begin + len(CODEX_ROUTER_BEGIN)
    before = content[:block_start]
    current = content[block_start:end]
    after = content[end:]
    new_block = f"\n{replacement}\n"
    return before + new_block + after, current != new_block


def _sync_codex_router_consumers(
    manifest: dict, repo_root: Path, check: bool
) -> list[str]:
    replacement = _render_codex_router_embed(manifest)
    failures: list[str] = []
    for relative_path in CODEX_ROUTER_CONSUMERS:
        absolute_path = repo_root / relative_path
        try:
            content = absolute_path.read_text()
        except FileNotFoundError:
            # In fresh target repos these consumer docs may not exist
            # yet (no CLAUDE.md, no docs/agentic/instructions.md). Treat
            # that as "nothing to sync" rather than a hard failure;
            # --check still flags it so CI can require both.
            if check:
                failures.append(f"missing codex router consumer: {absolute_path}")
            continue

        try:
            updated, changed = _replace_marked_block(content, replacement)
        except ValueError as exc:
            failures.append(f"{absolute_path}: {exc}")
            continue

        if check:
            if changed:
                failures.append(f"codex router drift detected: {absolute_path}")
            continue

        if changed:
            absolute_path.write_text(updated)
    return failures


def _load_skill(skills_source_root: Path, slug: str) -> tuple[dict, str]:
    """Read the canonical neutral layout: skill.yaml + body.md.

    Returns ``(structured_metadata, prose_body)``. Raises SystemExit
    with a precise message on missing or malformed files.
    """
    slug_dir = skills_source_root / slug
    skill_yaml = slug_dir / "skill.yaml"
    body_md = slug_dir / "body.md"
    if not skill_yaml.is_file():
        raise SystemExit(
            f"manifest references skill {slug!r} but canonical source is missing: {skill_yaml}"
        )
    if not body_md.is_file():
        raise SystemExit(
            f"manifest references skill {slug!r} but body.md is missing: {body_md}"
        )
    structured = yaml.safe_load(skill_yaml.read_text()) or {}
    if not isinstance(structured, dict):
        raise SystemExit(f"{skill_yaml}: must parse to a mapping")
    return structured, body_md.read_text()


def _strip_generator_metadata(structured: dict) -> tuple[dict, dict]:
    """Split canonical structured metadata from per-agent overrides.

    The neutral skill.yaml carries a top-level ``generator`` key whose
    children describe per-agent rendering hints
    (e.g. ``generator.claude_overrides.disable-model-invocation``).
    Returns ``(canonical, generator_block)`` where ``canonical`` is the
    structured manifest minus the generator block. The generator block
    is consumed by the per-agent renderers to compose agent-specific
    frontmatter.
    """
    if not isinstance(structured, dict):
        return {}, {}
    structured = dict(structured)
    generator = structured.pop("generator", {}) or {}
    if not isinstance(generator, dict):
        generator = {}
    return structured, generator


def _render_claude_skill(slug: str, structured: dict, body: str) -> str:
    """Compose Claude-shape SKILL.md from canonical skill.yaml + body.md.

    Re-attaches Claude-only frontmatter keys carried under
    ``generator.claude_overrides`` (e.g. ``disable-model-invocation``).
    """
    canonical, generator = _strip_generator_metadata(structured)
    overrides = generator.get("claude_overrides") or {}
    frontmatter = {**canonical, **overrides}
    fm_text = yaml.safe_dump(frontmatter, sort_keys=False, default_flow_style=False).rstrip()
    body = body if body.endswith("\n") else body + "\n"
    return f"---\n{fm_text}\n---\n\n{body}"


def _render_codex_skill(slug: str, structured: dict, body: str) -> str:
    """Compose Codex-shape SKILL.md.

    Codex skills carry the same YAML+Markdown shape as Claude. We keep
    only the canonical fields here — Codex doesn't honor Claude's
    ``disable-model-invocation`` knob, so we drop the
    ``generator.claude_overrides`` block.
    """
    canonical, _ = _strip_generator_metadata(structured)
    fm_text = yaml.safe_dump(canonical, sort_keys=False, default_flow_style=False).rstrip()
    body = body if body.endswith("\n") else body + "\n"
    return f"---\n{fm_text}\n---\n\n{body}"


def _expected_skill_outputs(
    manifest: dict,
    skills_source_root: Path,
    claude_skills_out: Path | None,
    codex_skills_out: Path | None,
) -> dict[Path, str]:
    """Map per-agent skill output paths to their generated content.

    WORKSTATE-REF-02 implementation note cutover: returns an empty mapping. The cross-harness
    `.claude/skills/<slug>/SKILL.md` and `.codex/skills/<slug>/SKILL.md`
    surfaces are owned by the plugin tree (ADR-001); the legacy mode no
    longer duplicates them per consumer. ``--claude-skills-out`` and
    ``--codex-skills-out`` are accepted (and the destinations are still
    pruned by ``_prune_stale_skill_dirs``) for backwards compatibility
    with existing operator scripts, but no new content is written.
    """
    # Loading every skill at runtime is no longer necessary now that the
    # legacy mode emits nothing here; the plugin-tree emission does its
    # own load via ``_render_skill_body``. Keeping the input parameters
    # so the call sites do not have to change.
    del manifest, skills_source_root, claude_skills_out, codex_skills_out
    return {}


def _write_skill_files(outputs: dict[Path, str]) -> None:
    """Write generated skill files; replace pre-existing symlinks
    pointing at a former canonical source.
    """
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        # If the parent directory used to be a symlink (legacy layout
        # where .codex/skills/<slug> linked to .claude/skills/<slug>),
        # replace it with a real directory.
        if path.parent.is_symlink():
            target = path.parent
            target.unlink()
            target.mkdir(parents=True, exist_ok=True)
        if path.is_symlink():
            path.unlink()
        # Codex output was previously emitted as lowercase skill.md.
        # On case-insensitive filesystems writing SKILL.md over an
        # existing skill.md preserves the lowercase casing, which
        # breaks Codex skill discovery. Remove any legacy lowercase
        # sibling before writing so the on-disk name is exactly SKILL.md.
        if path.name == "SKILL.md":
            legacy = path.with_name("skill.md")
            if legacy.is_symlink() or legacy.exists():
                legacy.unlink()
        path.write_text(content)


def _prune_stale_skill_dirs(
    out_root: Path | None, expected_slugs: set[str]
) -> None:
    """Remove generated skill directories whose slug is no longer in the manifest."""
    if out_root is None or not out_root.exists():
        return
    for entry in out_root.iterdir():
        if entry.name in expected_slugs:
            continue
        if entry.is_symlink() or entry.is_file():
            entry.unlink()
        else:
            shutil.rmtree(entry)


def _prune_legacy_portable_emissions(
    manifest: dict,
    claude_commands_out: Path | None,
    claude_skills_out: Path | None,
    codex_skills_out: Path | None,
) -> list[Path]:
    """Remove legacy emissions for portable command_ids / skill slugs.

    WORKSTATE-REF-02 implementation note stopped writing `.claude/commands/<id>.md`,
    `.claude/skills/<slug>/SKILL.md`, and `.codex/skills/<slug>/SKILL.md`
    for portable manifest entries; those surfaces are owned by the
    plugin tree now. ``_prune_stale_skill_dirs`` only removes slugs that
    were dropped from the manifest, so pre-existing legacy files for
    *still-portable* slugs would otherwise persist as duplicates of the
    plugin-tree content.

    Deletion is conservative:
      - ``.claude/commands/<id>.md``: only removed when the file starts
        with ``GENERATOR_TAG`` (same gate as ``_extra_generated_files``);
        hand-authored slash commands at the same id are left alone.
      - ``.claude/skills/<slug>/SKILL.md`` and ``.codex/skills/<slug>/SKILL.md``
        (plus the legacy lowercase ``skill.md`` sibling): removed only
        when the file's frontmatter ``name`` matches the portable slug,
        which is the shape every pre-cutover legacy emission has (the
        legacy generator copied ``skills/<slug>/body.md`` whose canonical
        frontmatter declares ``name: <slug>``). A file with a non-matching
        ``name`` is treated as a hand-authored project-local override and
        left alone — this is the BR-04 safety gate that keeps the prune
        helper from clobbering contributor files at colliding paths.
      - The parent slug directory is removed only when it becomes empty
        after the SKILL.md deletion, so user-added siblings are
        preserved.
    """
    removed: list[Path] = []
    for command in manifest["commands"]:
        command_id = command["command_id"]
        slug = command["skill"]
        if claude_commands_out is not None:
            legacy_command = claude_commands_out / f"{command_id}.md"
            if legacy_command.is_file():
                try:
                    if legacy_command.read_text().startswith(GENERATOR_TAG):
                        legacy_command.unlink()
                        removed.append(legacy_command)
                except OSError:
                    pass
        for skills_root in (claude_skills_out, codex_skills_out):
            if skills_root is None:
                continue
            skill_dir = skills_root / slug
            if not skill_dir.exists():
                continue
            for name in ("SKILL.md", "skill.md"):
                candidate = skill_dir / name
                if candidate.is_symlink() or candidate.is_file():
                    if _legacy_skill_matches_portable_slug(candidate, slug):
                        candidate.unlink()
                        removed.append(candidate)
            try:
                if not any(skill_dir.iterdir()):
                    skill_dir.rmdir()
                    removed.append(skill_dir)
            except OSError:
                pass
    return removed


def _legacy_skill_matches_portable_slug(path: Path, slug: str) -> bool:
    """Return True iff ``path`` looks like a pre-cutover legacy SKILL.md
    emission for ``slug`` — i.e. it has YAML frontmatter whose ``name``
    field equals the slug. A file at a portable slug path that declares a
    different ``name`` (or has no parseable frontmatter) is treated as a
    hand-authored project-local override and preserved.
    """
    try:
        text = path.read_text()
    except OSError:
        return False
    if not text.startswith("---\n"):
        return False
    try:
        _, fm_raw, _ = text.split("---\n", 2)
    except ValueError:
        return False
    try:
        frontmatter = yaml.safe_load(fm_raw) or {}
    except yaml.YAMLError:
        return False
    if not isinstance(frontmatter, dict):
        return False
    return frontmatter.get("name") == slug


def _check_skill_outputs(outputs: dict[Path, str]) -> list[str]:
    failures: list[str] = []
    for path, expected in outputs.items():
        if not path.exists():
            failures.append(f"missing generated skill file: {path}")
            continue
        if path.is_symlink():
            failures.append(
                f"generated skill path is a symlink (legacy layout): {path}"
            )
            continue
        # Case-insensitive filesystems resolve Path('SKILL.md') to an
        # on-disk skill.md, hiding stale lowercase emissions from the
        # drift gate. Codex skill discovery is case-sensitive, so verify
        # the actual directory entry name matches the expected casing.
        if path.parent.is_dir() and path.name not in {
            entry.name for entry in path.parent.iterdir()
        }:
            failures.append(
                f"generated skill file has wrong on-disk casing: {path} "
                f"(expected exact name {path.name!r})"
            )
            continue
        actual = path.read_text()
        if actual != expected:
            failures.append(f"drift detected: {path}")
    return failures


def _expected_outputs(
    manifest: dict,
    skills_source_root: Path,
    claude_out: Path,
    prompts_out: Path,
    codex_router_out: Path,
) -> dict[Path, str]:
    # WORKSTATE-REF-02 implementation note cutover: the cross-harness `.claude/commands/<id>.md`
    # surface for portable slugs is no longer emitted here — consumers
    # discover those slash commands from the plugin tree (ADR-001) and
    # the codex-command-router block. Only Copilot prompts and the
    # router doc are produced from this code path.
    outputs: dict[Path, str] = {}
    for command in manifest["commands"]:
        command_id = command["command_id"]
        structured, body = _load_skill(skills_source_root, command["skill"])
        outputs[prompts_out / f"{command_id}.prompt.md"] = _render_prompt_with_guidance(
            command,
            _extract_prompt_guidance(structured, body),
        )
    outputs[codex_router_out / "codex-command-router.md"] = _render_codex_router(
        manifest
    )
    return outputs


def _write_outputs(outputs: dict[Path, str]) -> None:
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


def _extra_generated_files(root: Path, expected_paths: set[Path]) -> list[Path]:
    if not root.exists():
        return []
    extras: list[Path] = []
    for path in root.rglob("*"):
        if not path.is_file():
            continue
        if path in expected_paths:
            continue
        try:
            content = path.read_text()
        except OSError:
            continue
        if content.startswith(GENERATOR_TAG):
            extras.append(path)
    return sorted(extras)


def _check_outputs(
    outputs: dict[Path, str],
    claude_out: Path,
    prompts_out: Path,
    codex_router_out: Path,
) -> int:
    failures: list[str] = []
    for path, expected in outputs.items():
        if not path.exists():
            failures.append(f"missing generated file: {path}")
            continue
        actual = path.read_text()
        if actual != expected:
            failures.append(f"drift detected: {path}")

    expected_paths = set(outputs)
    # WORKSTATE-REF-02 implementation note: claude_out is no longer manifest-driven (the
    # `.claude/commands/<id>.md` surface moved to the plugin tree), so
    # any tagged file under claude_out — e.g. the harness-only
    # `spec.md` — is intentionally outside this manifest's scope and
    # must not be flagged as stale here.
    extras = (
        _extra_generated_files(prompts_out, expected_paths)
        + _extra_generated_files(codex_router_out, expected_paths)
    )
    for path in extras:
        failures.append(f"stale generated file not declared in manifest: {path}")

    if failures:
        print(
            "Agent workflow adapters are out of sync with the manifest:",
            file=sys.stderr,
        )
        for failure in failures:
            print(f"  - {failure}", file=sys.stderr)
        return 1
    print("✓ agent-workflows: generated adapters match the manifest.")
    return 0


def _load_mcp_servers_manifest(path: Path) -> dict:
    """Load and shallow-validate mcp_servers.yaml (WORKSTATE-REF-01 input)."""
    try:
        payload = yaml.safe_load(path.read_text()) or {}
    except FileNotFoundError as exc:
        raise SystemExit(f"mcp_servers manifest not found: {path}") from exc
    if not isinstance(payload, dict):
        raise SystemExit(f"{path}: must parse to a mapping")
    if payload.get("version") != 1:
        raise SystemExit(f"{path}: must declare version=1; found {payload.get('version')!r}")
    plugin_version = payload.get("plugin_version")
    if not isinstance(plugin_version, str) or not plugin_version.strip():
        raise SystemExit(f"{path}: plugin_version must be a non-empty string")
    servers = payload.get("mcp_servers")
    if not isinstance(servers, list) or not servers:
        raise SystemExit(f"{path}: mcp_servers must be a non-empty list")
    for index, server in enumerate(servers):
        if not isinstance(server, dict):
            raise SystemExit(f"{path}: mcp_servers[{index}] must be a mapping")
        for field in ("name", "command"):
            value = server.get(field)
            if not isinstance(value, str) or not value.strip():
                raise SystemExit(
                    f"{path}: mcp_servers[{index}].{field} must be a non-empty string"
                )
        args = server.get("args", [])
        if not isinstance(args, list) or not all(isinstance(a, str) for a in args):
            raise SystemExit(
                f"{path}: mcp_servers[{index}].args must be a list of strings"
            )
        harnesses = server.get("harnesses", [])
        if not isinstance(harnesses, list) or not all(
            isinstance(h, str) for h in harnesses
        ):
            raise SystemExit(
                f"{path}: mcp_servers[{index}].harnesses must be a list of strings"
            )
    return payload


def _render_mcp_servers_json(mcp_manifest: dict, harness: str) -> str:
    """Render the .mcp.json blob for the requested harness.

    Servers whose ``harnesses`` list excludes the harness are skipped.
    Output ordering follows the manifest insertion order; each entry
    carries ``"type": "stdio"`` to stay compatible with the bootstrap
    install path.
    """
    entries: dict[str, dict] = {}
    for server in mcp_manifest["mcp_servers"]:
        harnesses = server.get("harnesses") or []
        if harnesses and harness not in harnesses:
            continue
        entries[server["name"]] = {
            "type": "stdio",
            "command": server["command"],
            "args": list(server.get("args", [])),
        }
        env = server.get("env")
        if isinstance(env, dict) and env:
            entries[server["name"]]["env"] = dict(env)
    payload = {"mcpServers": entries}
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def _render_plugin_manifest_json(plugin_version: str) -> str:
    """Render the metadata-only plugin.json (live-doc verified shape).

    Both ``.claude-plugin/plugin.json`` and ``.codex-plugin/plugin.json``
    share the same body — only the parent directory name differs per
    harness.
    """
    payload = {
        "name": _PLUGIN_NAME,
        "version": plugin_version,
        "description": _PLUGIN_DESCRIPTION,
        "skills": "./skills/",
        "mcpServers": "./.mcp.json",
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def _render_plugin_skill(structured: dict, body: str) -> str:
    """Render a SKILL.md body for the plugin tree.

    ADR-001 mandates byte-identical SKILL.md across harnesses, so this
    intentionally drops the ``generator.claude_overrides`` block.
    """
    canonical, _ = _strip_generator_metadata(structured)
    fm_text = yaml.safe_dump(canonical, sort_keys=False, default_flow_style=False).rstrip()
    body = body if body.endswith("\n") else body + "\n"
    return f"---\n{fm_text}\n---\n\n{body}"


def _sha256_digest(content: str) -> str:
    return f"sha256:{hashlib.sha256(content.encode('utf-8')).hexdigest()}"


