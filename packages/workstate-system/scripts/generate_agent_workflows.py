def _compose_plugin_skill_overrides(
    rendered_skills: dict[str, str],
    override_root: Path,
    payload: PluginOverrideManifest,
) -> tuple[dict[str, str], list[str], list[dict[str, str]]]:
    composed = dict(rendered_skills)
    skill_order = list(rendered_skills)
    components: list[dict[str, str]] = []

    skills = payload.components.skills
    for slug, override in sorted(skills.items()):
        mode = override.mode
        relative_path = override.path
        if mode == "replace":
            if slug not in composed:
                raise SystemExit(
                    f"{override_root / _PLUGIN_OVERRIDE_MANIFEST}: cannot replace unknown skill {slug!r}"
                )
            assert relative_path is not None
            upstream_digest = override.upstream_digest
            assert upstream_digest is not None
            base_digest = _sha256_digest(composed[slug])
            stale_component: dict[str, str] = {}
            if upstream_digest != base_digest:
                on_upstream_change = override.on_upstream_change
                if on_upstream_change == "warn":
                    stale_component = {
                        "status": "stale",
                        "override_path": relative_path,
                        "recorded_upstream_digest": upstream_digest,
                        "current_base_digest": base_digest,
                    }
                elif on_upstream_change != "ignore":
                    raise SystemExit(
                        f"{override_root / _PLUGIN_OVERRIDE_MANIFEST}: components.skills.{slug}.upstream_digest "
                        f"{upstream_digest!r} does not match current base digest {base_digest!r}"
                    )
            override_path = override_root / relative_path
            try:
                composed_skill = override_path.read_text()
            except FileNotFoundError as exc:
                raise SystemExit(f"plugin override skill not found: {override_path}") from exc
            composed[slug] = composed_skill
            components.append(
                {
                    "component_kind": "skill",
                    "name": slug,
                    "mode": "replace",
                    "effective_digest": _sha256_digest(composed_skill),
                    **stale_component,
                }
            )
            continue

        if mode == "add":
            if slug in composed:
                raise SystemExit(
                    f"{override_root / _PLUGIN_OVERRIDE_MANIFEST}: cannot add existing skill {slug!r}; "
                    "use mode=replace instead"
                )
            assert relative_path is not None
            override_path = override_root / relative_path
            try:
                composed_skill = override_path.read_text()
            except FileNotFoundError as exc:
                raise SystemExit(f"plugin override skill not found: {override_path}") from exc
            composed[slug] = composed_skill
            skill_order.append(slug)
            components.append(
                {
                    "component_kind": "skill",
                    "name": slug,
                    "mode": "add",
                    "effective_digest": _sha256_digest(composed_skill),
                }
            )
            continue

        if mode == "disable":
            if slug not in composed:
                raise SystemExit(
                    f"{override_root / _PLUGIN_OVERRIDE_MANIFEST}: cannot disable unknown skill {slug!r}"
                )
            del composed[slug]
            skill_order = [entry for entry in skill_order if entry != slug]
            components.append(
                {
                    "component_kind": "skill",
                    "name": slug,
                    "mode": "disable",
                    "effective_digest": _sha256_digest(f"disabled:{slug}\n"),
                }
            )
            continue

        raise SystemExit(
            f"{override_root / _PLUGIN_OVERRIDE_MANIFEST}: components.skills.{slug}.mode "
            f"must be one of 'replace', 'add', or 'disable' for the current composition slice; found {mode!r}"
        )

    return composed, skill_order, components


def _load_plugin_mcp_patch(override_root: Path, relative_path: str) -> PluginMcpServerPatch:
    path = override_root / relative_path
    try:
        payload = yaml.safe_load(path.read_text()) or {}
    except FileNotFoundError as exc:
        raise SystemExit(f"plugin override MCP patch not found: {path}") from exc
    try:
        return PluginMcpServerPatch.model_validate(payload)
    except ValidationError as exc:
        raise SystemExit(f"{path}: {exc}") from exc


def _canonical_mcp_server_digest(server: dict[str, object]) -> str:
    return _sha256_digest(json.dumps(server, sort_keys=True, ensure_ascii=False))


def _base_plugin_mcp_server(name: str, mode: str, server: dict[str, object] | None) -> dict[str, object]:
    if mode == "add":
        return {"name": name, "command": "", "args": []}
    if server is None:
        raise SystemExit(
            f"MCP server override references unknown canonical server {name!r}; use mode='add' to declare a new one"
        )
    return dict(server)


def _compose_plugin_mcp_overrides(
    mcp_manifest: dict,
    override_root: Path,
    payload: PluginOverrideManifest,
) -> tuple[dict, list[dict[str, str]], list[str]]:
    servers = [dict(server) for server in mcp_manifest["mcp_servers"]]
    by_name = {
        server["name"]: server
        for server in servers
        if isinstance(server.get("name"), str)
    }
    components: list[dict[str, str]] = []
    audit_lines: list[str] = []

    for name, override in sorted(payload.components.mcp_servers.items()):
        mode = override.mode
        if mode == "disable":
            if name not in by_name:
                raise SystemExit(
                    f"{override_root / _PLUGIN_OVERRIDE_MANIFEST}: cannot disable unknown MCP server {name!r}"
                )
            servers = [entry for entry in servers if entry.get("name") != name]
            by_name.pop(name, None)
            components.append(
                {
                    "component_kind": "mcp_server",
                    "name": name,
                    "mode": "disable",
                    "effective_digest": _sha256_digest(f"disabled:{name}\n"),
                }
            )
            audit_lines.append(f"mcp audit: {name} disabled")
            continue

        if mode not in {"patch", "add"}:
            raise SystemExit(
                f"{override_root / _PLUGIN_OVERRIDE_MANIFEST}: components.mcp_servers.{name}.mode "
                f"must be one of 'patch', 'disable', or 'add'; found {mode!r}"
            )

        server = by_name.get(name)
        if mode == "patch" and server is None:
            raise SystemExit(
                f"{override_root / _PLUGIN_OVERRIDE_MANIFEST}: cannot patch unknown MCP server {name!r}"
            )
        if mode == "add" and server is not None:
            raise SystemExit(
                f"{override_root / _PLUGIN_OVERRIDE_MANIFEST}: cannot add existing MCP server {name!r}; use mode='patch' or 'disable'"
            )
        if not override.requires_trust_ack:
            raise SystemExit(
                f"{override_root / _PLUGIN_OVERRIDE_MANIFEST}: components.mcp_servers.{name}.requires_trust_ack "
                "must be true before patching MCP command, args, or env"
            )

        assert override.patch_path is not None
        patch = _load_plugin_mcp_patch(override_root, override.patch_path)
        if patch.target_server != name:
            raise SystemExit(
                f"{override_root / override.patch_path}: target_server {patch.target_server!r} "
                f"does not match override key {name!r}"
            )

        composed = _base_plugin_mcp_server(name, mode, server)
        mutated_fields: list[str] = []
        disabled = False
        for op in patch.ops:
            if op.op == "replace_command":
                composed["command"] = op.value
                mutated_fields.append("command")
                continue
            if op.op == "replace_args":
                composed["args"] = list(op.value)
                mutated_fields.append("args")
                continue
            if op.op == "append_args":
                composed["args"] = [*list(composed.get("args", [])), *op.value]
                mutated_fields.append("args")
                continue
            if op.op == "upsert_env":
                env = dict(composed.get("env", {}))
                env[op.name] = op.value
                composed["env"] = env
                mutated_fields.append("env")
                continue
            if op.op == "remove_env":
                env = dict(composed.get("env", {}))
                env.pop(op.name, None)
                if env:
                    composed["env"] = env
                else:
                    composed.pop("env", None)
                mutated_fields.append("env")
                continue
            if op.op == "disable_server":
                if mode == "add":
                    raise SystemExit(
                        f"{override_root / override.patch_path}: disable_server cannot be used with components.mcp_servers.{name}.mode='add'"
                    )
                disabled = True
                break

        if disabled:
            servers = [entry for entry in servers if entry.get("name") != name]
            by_name.pop(name, None)
            components.append(
                {
                    "component_kind": "mcp_server",
                    "name": name,
                    "mode": "disable",
                    "effective_digest": _sha256_digest(f"disabled:{name}\n"),
                }
            )
            audit_lines.append(f"mcp audit: {name} disabled")
            continue

        command = composed.get("command")
        args = composed.get("args", [])
        if not isinstance(command, str) or not command:
            raise SystemExit(
                f"{override_root / override.patch_path}: composed MCP server {name!r} must set a non-empty command"
            )
        if not isinstance(args, list) or not all(isinstance(arg, str) for arg in args):
            raise SystemExit(
                f"{override_root / override.patch_path}: composed MCP server {name!r} must carry args as a list of strings"
            )

        if mode == "add":
            servers.append(composed)
        else:
            for index, existing in enumerate(servers):
                if existing.get("name") == name:
                    servers[index] = composed
                    break
        by_name[name] = composed
        unique_fields = [field for field in ("command", "args", "env") if field in mutated_fields]
        components.append(
            {
                "component_kind": "mcp_server",
                "name": name,
                "mode": mode,
                "effective_digest": _canonical_mcp_server_digest(composed),
            }
        )
        if unique_fields:
            audit_lines.append(f"mcp audit: {name} {', '.join(unique_fields)}")

    return {
        **mcp_manifest,
        "mcp_servers": servers,
    }, components, audit_lines


def _render_plugin_effective_lock_json(
    base_remote_sha: str,
    effective_root: Path,
    components: list[dict[str, str]],
) -> str:
    if len(base_remote_sha) != 40 or any(ch not in "0123456789abcdef" for ch in base_remote_sha):
        raise SystemExit(
            f"--plugin-base-remote-sha must be a 40-char lowercase git SHA; found {base_remote_sha!r}"
        )
    payload = PluginEffectiveLock.model_validate(
        {
        "schema_version": 1,
        "plugin": _PLUGIN_NAME,
        "base_remote_sha": base_remote_sha,
        "effective_root": ".",
        "components": components,
        }
    ).model_dump(mode="json")
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def _expected_plugin_outputs(
    manifest: dict,
    mcp_manifest: dict,
    skills_source_root: Path,
    plugin_out: Path,
    plugin_overrides: Path | None = None,
    plugin_base_remote_sha: str | None = None,
) -> tuple[dict[Path, str], list[str]]:
    """Map every emitted plugin-tree file to its rendered content.

    Layout per harness::

        <plugin_out>/<harness>/<plugin_dir>/plugin.json
        <plugin_out>/<harness>/.mcp.json
        <plugin_out>/<harness>/skills/<slug>/SKILL.md
    """
    outputs: dict[Path, str] = {}
    audit_lines: list[str] = []
    plugin_version = mcp_manifest["plugin_version"]
    plugin_manifest_body = _render_plugin_manifest_json(plugin_version)

    seen_slugs: list[str] = []
    rendered_skills: dict[str, str] = {}
    for command in manifest["commands"]:
        slug = command["skill"]
        if slug in rendered_skills:
            continue
        structured, body = _load_skill(skills_source_root, slug)
        rendered_skills[slug] = _render_plugin_skill(structured, body)
        seen_slugs.append(slug)

    effective_components: list[dict[str, str]] = []
    if plugin_overrides is not None:
        if plugin_base_remote_sha is None:
            raise SystemExit(
                "--plugin-base-remote-sha is required when --plugin-overrides is set"
            )
        override_payload = _load_plugin_override_manifest(plugin_overrides)
        rendered_skills, seen_slugs, effective_components = _compose_plugin_skill_overrides(
            rendered_skills, plugin_overrides, override_payload
        )
        mcp_manifest, mcp_components, audit_lines = _compose_plugin_mcp_overrides(
            mcp_manifest,
            plugin_overrides,
            override_payload,
        )
        effective_components.extend(mcp_components)

    for harness, plugin_dir in _PLUGIN_HARNESSES:
        harness_root = plugin_out / harness
        outputs[harness_root / plugin_dir / "plugin.json"] = plugin_manifest_body
        outputs[harness_root / ".mcp.json"] = _render_mcp_servers_json(
            mcp_manifest, harness
        )
        for slug in seen_slugs:
            outputs[harness_root / "skills" / slug / "SKILL.md"] = rendered_skills[slug]
    if plugin_overrides is not None:
        outputs[plugin_out / _PLUGIN_EFFECTIVE_LOCK] = _render_plugin_effective_lock_json(
            plugin_base_remote_sha,
            plugin_out,
            effective_components,
        )
    return outputs, audit_lines


def _extra_plugin_tree_files(plugin_out: Path, outputs: dict[Path, str]) -> list[Path]:
    if not plugin_out.exists():
        return []
    expected = {path.resolve() for path in outputs}
    return sorted(
        path
        for path in plugin_out.rglob("*")
        if path.is_file() and path.resolve() not in expected
    )


def _prune_plugin_tree(plugin_out: Path, outputs: dict[Path, str]) -> None:
    for path in _extra_plugin_tree_files(plugin_out, outputs):
        path.unlink()
    if not plugin_out.exists():
        return
    for path in sorted(plugin_out.rglob("*"), key=lambda item: len(item.parts), reverse=True):
        if not path.is_dir():
            continue
        try:
            path.rmdir()
        except OSError:
            continue


def _emit_plugin_tree(plugin_out: Path, outputs: dict[Path, str]) -> None:
    """Write every plugin-tree file deterministically."""
    _prune_plugin_tree(plugin_out, outputs)
    for path, content in sorted(outputs.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


def _check_plugin_outputs(plugin_out: Path, outputs: dict[Path, str]) -> list[str]:
    failures: list[str] = []
    for path, expected in sorted(outputs.items()):
        if not path.exists():
            failures.append(f"missing plugin tree file: {path}")
            continue
        if path.read_text() != expected:
            failures.append(f"plugin tree drift: {path}")
    for path in _extra_plugin_tree_files(plugin_out, outputs):
        failures.append(f"unexpected plugin tree file: {path}")
    return failures


def _run_plugin_mode(args: argparse.Namespace, package_root: Path, manifest: dict) -> int:
    skills_source_root = (
        args.skills_source_root
        or args.claude_skills_root
        or (package_root / "skills")
    )
    mcp_servers_path = args.plugin_mcp_servers or (
        package_root / "config" / "agent-workflows" / "mcp_servers.yaml"
    )
    if args.plugin_out is None:
        raise SystemExit("--mode=plugin requires --plugin-out <dest>")
    mcp_manifest = _load_mcp_servers_manifest(mcp_servers_path)
    outputs, audit_lines = _expected_plugin_outputs(
        manifest,
        mcp_manifest,
        skills_source_root,
        args.plugin_out,
        args.plugin_overrides,
        args.plugin_base_remote_sha,
    )
    stale_components: list[dict[str, object]] = []
    lock_payload = outputs.get(args.plugin_out / _PLUGIN_EFFECTIVE_LOCK)
    if lock_payload is not None:
        try:
            parsed_lock = json.loads(lock_payload)
        except json.JSONDecodeError:
            parsed_lock = {}
        stale_components = [
            entry
            for entry in parsed_lock.get("components", [])
            if isinstance(entry, dict) and entry.get("status") == "stale"
        ]
    if args.check:
        failures = _check_plugin_outputs(args.plugin_out, outputs)
        if stale_components:
            print("Plugin override composition has stale overrides:", file=sys.stderr)
            for entry in stale_components:
                print(
                    "  - stale override: "
                    f"{entry.get('override_path')} "
                    f"(recorded {entry.get('recorded_upstream_digest')} vs current {entry.get('current_base_digest')})",
                    file=sys.stderr,
                )
        if failures:
            print("Plugin tree is out of sync with the canonical inputs:", file=sys.stderr)
            for failure in failures:
                print(f"  - {failure}", file=sys.stderr)
        if failures or stale_components:
            return 1
        print(f"✓ plugin-tree: {len(outputs)} files match canonical inputs.")
        return 0
    _emit_plugin_tree(args.plugin_out, outputs)
    for line in audit_lines:
        print(line)
    if stale_components:
        for entry in stale_components:
            print(
                "warning: stale override preserved: "
                f"{entry.get('override_path')} "
                f"(recorded {entry.get('recorded_upstream_digest')} vs current {entry.get('current_base_digest')})",
                file=sys.stderr,
            )
    print(f"✓ plugin-tree: wrote {len(outputs)} files under {args.plugin_out}.")
    return 0


def main() -> int:
    args = _parse_args()
    manifest = _load_manifest(args.manifest)
    package_root = args.manifest.resolve().parents[2]

    if args.mode == "plugin":
        return _run_plugin_mode(args, package_root, manifest)

    # Source-of-truth: skills/<slug>/{skill.yaml, body.md}.
    # --claude-skills-root is the legacy alias kept for one release.
    skills_source_root = (
        args.skills_source_root
        or args.claude_skills_root
        or (package_root / "skills")
    )

    # Per-agent output paths. --target is sugar for "set every per-agent
    # output to this consumer repo's standard location"; explicit
    # per-agent flags still override.
    target = args.target
    claude_out = args.claude_out or (target / ".claude" / "commands" if target else None)
    claude_skills_out = args.claude_skills_out or (
        target / ".claude" / "skills" if target else None
    )
    prompts_out = args.prompts_out or (target / ".github" / "prompts" if target else None)
    codex_router_out = args.codex_router_out or (
        target / "docs" / "agentic" / "generated" if target else None
    )
    codex_skills_out = args.codex_skills_out or (
        target / ".codex" / "skills" if target else None
    )

    # When invoked without --target and without explicit out paths
    # (e.g. workstate-system source-of-truth context), fall back to
    # package-internal sentinel paths so --check still has something
    # to validate against. Writes will refuse to land here.
    if claude_out is None:
        claude_out = package_root / ".claude" / "commands"
    if prompts_out is None:
        prompts_out = package_root / ".github" / "prompts"
    if codex_router_out is None:
        codex_router_out = package_root / "docs" / "agentic" / "generated"

    outputs = _expected_outputs(
        manifest,
        skills_source_root,
        claude_out,
        prompts_out,
        codex_router_out,
    )
    skill_outputs = _expected_skill_outputs(
        manifest, skills_source_root, claude_skills_out, codex_skills_out
    )

    # repo_root for the codex-router-consumers sync is the target repo
    # if --target was given, otherwise the package root.
    repo_root = target if target is not None else package_root

    if args.check_codex_router_blocks:
        failures = _sync_codex_router_consumers(manifest, repo_root, check=True)
        if failures:
            print(
                "Codex router consumer docs are out of sync with the manifest:",
                file=sys.stderr,
            )
            for failure in failures:
                print(f"  - {failure}", file=sys.stderr)
            return 1
        print("✓ codex-router: consumer docs match the manifest-rendered block.")
        return 0

    if args.check:
        exit_code = _check_outputs(outputs, claude_out, prompts_out, codex_router_out)
        skill_failures = _check_skill_outputs(skill_outputs)
        if skill_failures:
            print(
                "Generated skill files are out of sync with the manifest:",
                file=sys.stderr,
            )
            for failure in skill_failures:
                print(f"  - {failure}", file=sys.stderr)
            exit_code = 1
        return exit_code

    _write_outputs(outputs)
    failures = _sync_codex_router_consumers(manifest, repo_root, check=False)
    if failures:
        raise SystemExit("\n".join(failures))
    _write_skill_files(skill_outputs)
    expected_slugs = {command["skill"] for command in manifest["commands"]}
    _prune_stale_skill_dirs(claude_skills_out, expected_slugs)
    _prune_stale_skill_dirs(codex_skills_out, expected_slugs)
    _prune_legacy_portable_emissions(
        manifest, claude_out, claude_skills_out, codex_skills_out
    )
    total = len(outputs) + len(skill_outputs)
    print(f"✓ agent-workflows: wrote {total} adapter files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
